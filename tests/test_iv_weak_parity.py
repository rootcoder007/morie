@pytest.mark.parametrize("vcov", ["robust", "iid", "cluster"])
def test_kleibergen_paap_matches_the_r_arm(vcov):
    r = kleibergen_paap(DATA, ["x", "x2"], ["z1", "z2"], ["w"], vcov=vcov, cluster="cl")
    expect = {"robust": KP_robust, "iid": KP_iid, "cluster": KP_cluster}[vcov]
    assert [r["statistic"], r["chi2_statistic"]] == pytest.approx(expect, rel=1e-10)
    assert r["df"] == 1


@pytest.mark.parametrize("vcov", ["robust", "iid", "cluster", "hac"])
def test_montiel_olea_pflueger_matches_the_r_arm(vcov):
    r = montiel_olea_pflueger(DATA, "y", "x", ["z1", "z2"], ["w"], vcov=vcov, cluster="cl")
    expect = {"robust": MOP_robust, "iid": MOP_iid, "cluster": MOP_cluster, "hac": MOP_hac}[vcov]
    c = r["critical_values"][1]
    got = [r["F_eff"], r["B_tsls"], r["B_liml"], c["tsls"], c["liml"], c["simplified"]]
    assert got[0] == pytest.approx(expect[0], rel=1e-10)
    # the sup over beta is polished by a one-dimensional search, which differs between the arms
    assert got[1:] == pytest.approx(expect[1:], abs=1e-6)


def test_iv_module_wrappers_and_refusals():
    r = iv.kleibergen_paap_test(DATA, ["x", "x2"], ["z1", "z2"], ["w"])
    assert r.statistic == pytest.approx(KP_robust[0], rel=1e-10)
    assert r.critical_values == {"rule_of_thumb": 10.0}
    m = iv.montiel_olea_pflueger_test(DATA, "y", "x", ["z1", "z2"], ["w"])
    assert m.statistic == pytest.approx(MOP_robust[0], rel=1e-10)
    assert m.critical_values["tau_10"] == pytest.approx(MOP_robust[3], abs=1e-6)
    with pytest.raises(ValueError, match="one endogenous"):
        montiel_olea_pflueger(DATA, "y", ["x", "x2"], ["z1", "z2"])
    with pytest.raises(ValueError, match="needs `cluster`"):
        kleibergen_paap(DATA, ["x"], ["z1"], vcov="cluster")
    with pytest.raises(ValueError, match="not in `data`"):
        kleibergen_paap(DATA, ["nope"], ["z1"])
