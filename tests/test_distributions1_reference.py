@pytest.mark.parametrize("name", sorted(PINS))
def test_distribution_matches_r_and_is_consistent(name):
    c = PINS[name]
    f = getattr(importlib.import_module(f"morie.fn.{name}"), name)
    r = f(x=c["x"], p=c["p"], n=3, seed=5, **c["par"])
    for got, ref in zip(r["pdf"] + r["cdf"] + r["quantile"], c["pdf"] + c["cdf"] + c["q"]):
        assert abs(got - ref) <= 1e-10 * max(1.0, abs(ref))
    for got, ref in zip(r["random"], c["rand"]):
        assert abs(got - ref) <= 1e-10 * max(1.0, abs(ref))  # Philox draws, identical in the R arm
    # the quantile inverts the distribution function
    back = f(x=r["quantile"], **c["par"])["cdf"]
    assert max(abs(a - b) for a, b in zip(back, c["p"])) < 1e-9
    # the density is the derivative of the distribution function
    for v, d in zip(r["quantile"], f(x=r["quantile"], **c["par"])["pdf"]):
        h = 1e-5 * max(1.0, abs(v))
        lo, hi = f(x=[v - h, v + h], **c["par"])["cdf"]
        assert abs((hi - lo) / (2 * h) - d) < 1e-5 * max(1.0, d)
    # and integrates to the distribution function between two quantiles
    a, b = r["quantile"][0], r["quantile"][-1]
    dens = lambda t: f(x=t, **c["par"])["pdf"]  # noqa: E731
    k = c["par"].get("loc")
    if k is not None and a < k < b:  # the Laplace densities have a kink at loc: integrate each smooth piece
        area = gauss_legendre(dens, a, k, n=200) + gauss_legendre(dens, k, b, n=200)
    else:
        area = gauss_legendre(dens, a, b, n=200)
    assert abs(area - (c["p"][-1] - c["p"][0])) < 1e-8


def test_discrete_and_lambda_families():
    import math

    from morie.fn.categoricaldist import categoricaldist
    from morie.fn.genlambda import genlambda
    from morie.fn.orderedlogis import orderedlogis
    from morie.fn.ricedist import ricedist
    from morie.fn.tukeylambda import tukeylambda

    r = ricedist([0.3, 1.2, 3.1], sigma=1.3, vee=1.7, p=[0.1, 0.5, 0.93])
    for got, ref in zip(
        r["pdf"] + r["cdf"] + r["quantile"],
        (
            0.0751913285322813,
            0.2758652466043360,
            0.2441715259025328,
            0.0113014618917644,
            0.1740022716113704,
            0.7825006657103627,
            0.900741226929325,
            2.183216098941224,
            3.949005405229531,
        ),
    ):
        assert abs(got - ref) < 1e-12 * max(1, ref)  # VGAM::drice, price, qrice
    assert abs(ricedist(60.0, sigma=1.0, vee=60.0)["pdf"] - 0.398956134728945) < 1e-12  # asymptotic log I0 branch
    assert abs(ricedist(1.0, sigma=1.0)["cdf"] - (1 - math.exp(-0.5))) < 1e-13  # vee = 0 is Rayleigh
    g = genlambda([0.5, 1.0, 1.6], l1=1.0, l2=0.2, l3=0.13, l4=0.3, p=[0.1, 0.5, 0.93])
    for got, ref in zip(
        g["pdf"] + g["cdf"] + g["quantile"],
        (
            0.241029575395583,
            0.275246511092220,
            0.272854411982150,
            0.228190633605884,
            0.358709133054606,
            0.525277092171254,
            -0.137879599481729,
            1.507895269365825,
            3.701408470725271,
        ),
    ):
        assert abs(got - ref) < 1e-12 * max(1, abs(ref))  # gld::dgl/pgl/qgl, param = "rs"
    t = tukeylambda([-0.5, 0.3, 2.0], lam=0.14)
    for got, ref in zip(
        t["pdf"] + t["cdf"],
        (
            0.259269390430479,
            0.269524508893164,
            0.105909395127012,
            0.364996897516401,
            0.582045019626757,
            0.915377806611856,
        ),
    ):
        assert abs(got - ref) < 1e-12  # gld with l1 = 0, l2 = l3 = l4 = 0.14
    assert (
        tukeylambda(0.25, lam=1.0)["cdf"] == 0.625 and abs(tukeylambda(0.0, lam=0.0)["pdf"] - 0.25) < 1e-15
    )  # uniform; logistic
    o = orderedlogis([0, 2, 3], eta=0.3, cuts=[-1, 0.5, 2])
    F = lambda v: 1 / (1 + math.exp(-v))  # noqa: E731
    assert abs(o["pmf"][0] - F(-1.3)) < 1e-15 and abs(o["pmf"][1] - (F(1.7) - F(0.2))) < 1e-15 and o["cdf"][2] == 1.0
    assert sorted(set(orderedlogis(eta=0.3, cuts=[-1, 0.5, 2], n=200, seed=3)["random"])) == [0, 1, 2, 3]
    c = categoricaldist([0, 1, 2], probs=[1, 2, 5], n=4000, seed=7)
    assert c["pmf"] == [0.125, 0.25, 0.625] and abs(c["mean"] - 1.5) < 1e-15
    freq = sum(v == 2 for v in c["random"]) / 4000
    assert abs(freq - 0.625) < 4 * (0.625 * 0.375 / 4000) ** 0.5
