def _same(a, b):
    assert len(a) == len(b)
    for x, y in zip(a, b):
        if y != y:
            assert x != x
        else:
            assert x == pytest.approx(y, rel=1e-12, abs=1e-12)


@pytest.mark.parametrize("grid,ref,d", [(GRID_B, REF_B, 8), (GRID_C, REF_C, 4)])
def test_metrics_equal_landscapemetrics(grid, ref, d):
    out = {
        "p": patch_metrics(grid, res=2.0, directions=d),
        "c": class_metrics(grid, res=2.0, directions=d),
        "l": landscape_metrics(grid, res=2.0, directions=d),
    }
    for (lv, mt), want in ref.items():
        got = out[lv][mt]
        _same(got if isinstance(got, list) else [got], want)


def test_patch_labels_are_column_major_within_class():
    lab = label_patches([[1, 1, 2], [2, 1, 2]], directions=4)
    assert lab.labels == [[1, 1, 3], [2, 1, 3]]
    assert lab.patch_class == [1, 2, 2]
    assert label_patches([[1, 0], [0, 1]], directions=8).patch_class == [0, 1]


def test_fragstats_clumpy_ai_and_diversity_by_hand():
    # class 3 is three isolated cells: g_33 = 0 < P_3 < 1/2 gives CLUMPY = -1 (FRAGSTATS)
    g = [[1, 1, 2, 2], [1, 3, 2, 2], [1, 1, 3, 2], [3, 1, 2, 2]]
    c = class_metrics(g, directions=4)
    assert c.clumpy[2] == pytest.approx(-1.0, abs=1e-15)
    # a solid 3 x 3 block: all possible like adjacencies, AI = 100
    s = class_metrics([[1, 1, 1, 2], [1, 1, 1, 2], [1, 1, 1, 2]], directions=4)
    assert s.ai[0] == pytest.approx(100.0, abs=1e-12)
    L = landscape_metrics(g, directions=4)
    p = [c.pland[i] / 100 for i in range(3)]
    assert L.shdi == pytest.approx(-sum(v * math.log(v) for v in p), abs=1e-15)
    assert L.dominance == pytest.approx(math.log(3) - L.shdi, abs=1e-15)
    assert L.sidi == pytest.approx(1 - sum(v * v for v in p), abs=1e-15)
    assert L.pr == 3


def test_validation():
    with pytest.raises(ValueError):
        label_patches([[1, 2], [1]])
    with pytest.raises(ValueError):
        label_patches([[1]], directions=6)
