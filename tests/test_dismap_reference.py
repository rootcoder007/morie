E = [p * sum(Y) / sum(POP) for p in POP]


def test_eb_global_local_and_probability_map_equal_spdep():
    assert eb_global(Y, POP).estimate == pytest.approx(EBEST, abs=1e-15)
    assert eb_local(Y, POP, NB).estimate == pytest.approx(EBLOCAL, abs=1e-15)
    assert probability_map(Y, POP).pmap == pytest.approx(PMAP, abs=1e-14)
    g = probability_map(Y, POP, alternative="greater").pmap
    assert g[0] == pytest.approx(
        1 - math.exp(-E[0]) * sum(E[0] ** k / math.factorial(k) for k in range(Y[0])), abs=1e-12
    )


def test_poisson_gamma_eb_equals_spatialepi():
    r = poisson_gamma_eb(Y, E, threshold=1.2)
    assert r.alpha == pytest.approx(EBAYES["alpha"], rel=1e-8)
    assert r.beta[0] == pytest.approx(EBAYES["beta"], abs=1e-9)
    assert pytest.approx(EBAYES["RR"], abs=1e-9) == r.RR
    assert r.RRmed == pytest.approx(EBAYES["RRmed"], abs=1e-9)
    assert r.exceedance == pytest.approx(EBAYES["thresh"], abs=1e-9)
    rx = poisson_gamma_eb(Y, E, [[v] for v in X])
    assert rx.alpha == pytest.approx(EBAYES["alphax"], rel=1e-8)
    assert pytest.approx(EBAYES["RRx"], abs=1e-9) == rx.RR


def test_expected_counts_and_exact_limits():
    # SpatialEpi::expected(c(100, 50, 30, 200, 50, 60, 80, 90, 10), c(1, 2, 3, 3, 3, 1, 0, 4, 2), 3)
    e = expected_counts([[100, 50, 30], [200, 50, 60], [80, 90, 10]], [[1, 2, 3], [3, 3, 1], [0, 4, 2]])
    assert e == pytest.approx([5.2210526315789476, 8.0736842105263165, 5.7052631578947368], abs=1e-14)
    # poisson.test(7, 5.5)$conf.int
    r = standardized_ratio([7, 0], [5.5, 2.0])
    assert (r.lower[0], r.upper[0]) == pytest.approx((0.5117024, 2.6223046), abs=1e-7)
    assert r.lower[1] == 0.0 and r.upper[1] == pytest.approx(-math.log(0.025) / 2.0, abs=1e-12)


def test_validation():
    with pytest.raises(ValueError):
        probability_map(Y, POP, alternative="two.sided")
