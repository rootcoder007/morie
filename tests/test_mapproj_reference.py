@pytest.mark.parametrize("proj", sorted(PROJ))
def test_projections_equal_proj(proj):
    for (lon, lat), want in zip(PROJ[proj]["pts"], PROJ[proj]["xy"]):
        assert map_project(lon, lat, proj, **ARGS.get(proj, {})).xy == pytest.approx(want, abs=1e-6)


def test_utm_and_zones():
    for (lon, lat), want in zip([PTS[0], PTS[1], PTS[3]], UTM33):
        assert map_project(lon, lat, "utm", zone=33).xy == pytest.approx(want, abs=1e-6)
    assert [
        utm_zone(10.0, 50.0),
        utm_zone(5.0, 60.0),
        utm_zone(10.0, 75.0),
        utm_zone(-180.0, 0.0),
        utm_zone(179.9, 0.0),
    ] == [32, 32, 33, 1, 60]


def test_geodesics_equal_geosphere():
    for i in range(7):
        (lo1, la1), (lo2, la2) = PTS[i], PTS[i + 1]
        v = vincenty_inverse(lo1, la1, lo2, la2)
        assert v.distance == pytest.approx(VINCENTY[i], abs=1e-3)
        assert v.azimuth1 == pytest.approx(BEARING[i], abs=1e-7)
        assert great_circle_distance(lo1, la1, lo2, la2) == pytest.approx(HAVERSINE[i], abs=1e-6)
    # one degree along the equator is a * pi / 180
    assert vincenty_inverse(0.0, 0.0, 1.0, 0.0).distance == pytest.approx(6378137.0 * math.pi / 180, abs=1e-6)


def test_ecef_and_enu():
    r = geodetic_to_enu(10.02, 50.01, 350.0, 10.0, 50.0, 300.0)
    assert r.ecef == pytest.approx(ECEF, abs=1e-6)
    up = geodetic_to_enu(10.0, 50.0, 350.0, 10.0, 50.0, 300.0).enu
    assert up == pytest.approx([0.0, 0.0, 50.0], abs=1e-8)
    e, n, _ = r.enu
    assert e > 0 and n > 0


