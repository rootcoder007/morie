@pytest.mark.parametrize("kind", ["ratio", "interval", "ordinal"])
def test_smacof_equals_smacofsym(kind):
    ref = {"ratio": SMACOF_ratio, "interval": SMACOF_interval, "ordinal": SMACOF_ordinal}[kind]
    r = smacof(D, type=kind)
    assert r.stress == pytest.approx(ref["stress"], abs=1e-12)
    assert r.niter == ref["niter"]
    assert r.confdist == pytest.approx(ref["confdist"], abs=1e-12)
    assert r.dhat == pytest.approx(ref["dhat"], abs=1e-12)
    assert sum(r.spp) == pytest.approx(100.0, abs=1e-12)


def test_smacof_missing_dissimilarity():
    Dm = [row[:] for row in D]
    Dm[3][7] = Dm[7][3] = float("nan")
    r = smacof(Dm, type="ordinal")
    assert r.stress == pytest.approx(SMACOF_missing["stress"], abs=1e-12)
    assert r.niter == SMACOF_missing["niter"]
    # a zero weight removes the pair from the stress
    W = [[1.0] * 10 for _ in range(10)]
    W[3][7] = W[7][3] = 0.0
    # pair (7, 3) is position 27 in R dist order
    assert smacof(D, type="ratio", weights=W).weights[27] == 0.0


def test_smacof_is_exact_on_euclidean_distances():
    E = [[0, 3, 4, 5], [3, 0, 5, 4], [4, 5, 0, 3], [5, 4, 3, 0]]
    assert smacof(E).stress == pytest.approx(0.0, abs=1e-12)
    assert round(smacof([[0, 3, 4, 6], [3, 0, 5, 4], [4, 5, 0, 3], [6, 4, 3, 0]]).stress, 6) == 0.049612


def test_procrustes_equals_vegan():
    p = procrustes_fit(X, Y)
    assert p.ss == pytest.approx(PROC["ss"], abs=1e-13)
    assert p.scale == pytest.approx(PROC["scale"], abs=1e-14)
    assert p.residuals == pytest.approx(PROC["residuals"], abs=1e-13)
    assert p.correlation == pytest.approx(PROC["r"], abs=1e-13)
    q = procrustes_fit([[0, 0], [1, 0], [0, 1]], [[0, 0], [0, 2], [-2, 0]])
    assert (q.ss, q.scale, q.correlation) == pytest.approx((0.0, 0.5, 1.0), abs=1e-12)


def test_generalized_procrustes_recovers_rotated_copies():
    th = 0.7
    R = [[math.cos(th), -math.sin(th)], [math.sin(th), math.cos(th)]]
    A = [list(r) for r in X]
    B = [[a * R[0][0] + b * R[1][0] + 5, a * R[0][1] + b * R[1][1] - 2] for a, b in A]
    g = generalized_procrustes([A, B])
    assert g.rss == pytest.approx(0.0, abs=1e-12)
    h = generalized_procrustes([X, Y, [[a + b, a - b] for a, b in X]])
    assert h.rss > 0 and h.iterations >= 1


def test_embedding_quality_by_hand():
    line = [[abs(i - j) for j in range(6)] for i in range(6)]
    e = embedding_quality(line, line, 2)
    assert (e.trustworthiness, e.continuity, e.qnx) == (1.0, 1.0, 1.0)
    assert e.lcmc == pytest.approx(1.0 - 2 / 5, abs=1e-15)
    # swap two points in the embedding: point 0's nearest neighbour becomes point 2 (true rank 2)
    emb = [0, 2, 1, 3, 4, 5]
    low = [[abs(emb[i] - emb[j]) for j in range(6)] for i in range(6)]
    e1 = embedding_quality(line, low, 1)
    assert e1.trustworthiness < 1.0 and e1.continuity < 1.0


def test_alienation_and_dissimilarity_checks():
    a = [1.0, 2.0, 3.0]
    b = [1.1, 1.9, 3.2]
    mu = sum(x * y for x, y in zip(a, b)) / math.sqrt(sum(x * x for x in a) * sum(y * y for y in b))
    assert alienation_coefficient(a, b) == pytest.approx(math.sqrt(1 - mu * mu), abs=1e-15)
    c = dissimilarity_check([[0, 1, 5], [1, 0, 1], [5, 1, 0]])
    assert (c.triangle_violations, c.max_violation, c.euclidean) == (1, 3.0, False)
    e = dissimilarity_check([[0, 3, 4, 5], [3, 0, 5, 4], [4, 5, 0, 3], [5, 4, 3, 0]])
    assert e.triangle_violations == 0 and e.euclidean and e.symmetric


