ALL_IDS = sorted(CASES)


@pytest.mark.parametrize("mid", ALL_IDS)
def test_front(mid):
    args, want = CASES[mid]
    res = call(mid, *args)
    if want is not None:
        assert res["value"] == pytest.approx(want, rel=2e-3, abs=2e-3)
    else:
        assert np.isfinite(res["value"])


def test_all_150_covered():
    assert len(CASES) == 150
    # chapter census: matches the stub inventory exactly
    from collections import Counter
    census = Counter(int(m[2:].split("e")[0]) for m in CASES)
    assert census == {1: 4, 2: 22, 3: 2, 4: 18, 5: 9, 6: 8, 7: 16, 8: 7,
                      9: 13, 10: 1, 11: 46, 12: 4}


def test_cross_module_consistency():
    # eq (11.5) inverts eq (11.6)/(9.3): d from t equals d from summary stats
    t = call("ca9e3", 127.8, 132.3, 10.4, 9.8, 25, 30)["value"]
    d_direct = call("ca11e1", 127.8, 132.3, 10.4, 9.8, 25, 30)["value"]
    d_from_t = call("ca11e5", t, 25, 30)["value"]
    assert d_from_t == pytest.approx(d_direct, rel=1e-9)
    # eq (11.28) and (11.29) are mutual inverses
    rr = call("ca11e8", 40, 60, 55, 45)["value"]
    or_ = call("ca11e28", rr, 0.55)["value"]
    assert call("ca11e29", or_, 0.55)["value"] == pytest.approx(rr, rel=1e-9)
    # eq (3.2) is the reciprocal of eq (3.1)
    tol = call("ca3e1", 0.2)["value"]
    assert call("ca3e2", 0.2)["value"] == pytest.approx(1 / tol, rel=1e-12)
    # Q partition: eq (11.46) = Q_total - eq (11.45)
    grp = ([[0.1, 0.2, 0.3], [0.5, 0.6]], [[10.0, 12.0, 9.0], [8.0, 11.0]])
    qw = call("ca11e45", *grp)
    qb = call("ca11e46", *grp)
    assert qw["q_total"] == pytest.approx(qw["q_within"] + qb["q_between"],
                                          rel=1e-9)
