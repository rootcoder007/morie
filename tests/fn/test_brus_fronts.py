def test_cross_module_consistency():
    # eq (6.4) pps form equals eq (6.9) SI form for equal cluster sizes
    pps = call("6e4", [7.0, 11.0], [2.0, 2.0], 6.0, 2)["value"]
    si = call("6e9", [7.0, 11.0], 3, 2)["value"]
    assert pps == pytest.approx(si, rel=1e-12)
    # kriging: variance forms agree through gamma = sill - C
    s = np.array([0.0, 10.0, 20.0])
    dm = np.abs(s[:, None] - s[None, :])
    cov = np.where(dm == 0, 2.0, 2.0 * np.exp(-dm / 15.0))
    cov0 = 2.0 * np.exp(-np.abs(s - 12.0) / 15.0)
    sol = call("21e4", cov, cov0)
    lam = np.array(sol["lam"])
    v_c = call("21e8", 2.0, lam, cov0, sol["nu"])["value"]
    v_g = call("21e11", lam, 2.0 - cov0, -sol["nu"])["value"]
    assert v_c == pytest.approx(v_g, rel=1e-9)
    assert lam.sum() == pytest.approx(1.0, rel=1e-9)
    # eq (26.3) = sigma2 / eq (26.4)
    v = call("26e3", 4.0, 8, 0.2)["value"]
    ne = call("26e4", 8, 0.2)["value"]
    assert v == pytest.approx(4.0 / ne, rel=1e-12)
