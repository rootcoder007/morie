@pytest.mark.parametrize("mid", sorted(CASES))
def test_front(mid):
    args, want = CASES[mid]
    res = call(mid, *args)
    if want is not None:
        assert res["value"] == pytest.approx(want, rel=2e-3, abs=2e-3)
    else:
        assert np.isfinite(res["value"])


def test_all_97_covered():
    assert len(CASES) == 97
