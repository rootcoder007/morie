r"""SchNet: continuous-filter convolutions for atoms.

A convolution assumes a grid. Atoms have arbitrary positions, so a
discrete filter indexed by grid offsets has nothing to index. SchNet's
answer is a **continuous-filter convolutional layer**: the filter is a
*function* of the interatomic distance, evaluated wherever the atoms
happen to be,

.. math:: x_i^{l+1} = \sum_{j} x_j^l \circ W^l\big(r_i - r_j\big),

with :math:`W^l` generated by a small network from the distance rather
than stored as weights per offset.

**Two symmetries, and they are different.** Energy must be
**rotationally invariant** -- turning the molecule cannot change it --
while forces must be **rotationally equivariant**, turning with it.
SchNet gets both from one design decision: the filter sees only
:math:`\|r_i - r_j\|`, so everything built from it is invariant, and
forces are then obtained as
:math:`F_i = -\partial E/\partial r_i`, which is equivariant
automatically because the derivative of an invariant scalar with
respect to a position is a vector. Predicting forces by a separate
head would lose that, and would also permit a non-conservative force
field.

**The distance expansion is what makes the filter smooth.** A raw
distance fed to a network gives a filter that varies too sharply; the
distance is expanded in a basis of Gaussians on a grid of centres,
:math:`e_k(r) = \exp(-\gamma(r - \mu_k)^2)`, which decorrelates the
input and makes the learned filter smooth in :math:`r`. A smooth filter
matters physically: energies and forces must be smooth in the atomic
positions or the model cannot be used for molecular dynamics at all.

**A cosine cutoff** ensures that an atom entering the neighbourhood
does so continuously rather than by a step.

References
----------
Schutt, K. T., Kindermans, P.-J., Sauceda, H. E., Chmiela, S.,
Tkatchenko, A. & Muller, K.-R. (2017) "SchNet: A continuous-filter
convolutional neural network for modeling quantum interactions",
*Advances in Neural Information Processing Systems 30 (NeurIPS 2017)*,
991-1001, arXiv:1706.08566. The key contributions as stated: the
continuous-filter convolutional (cfconv) layer as a means to move
beyond grid-bound data such as images or audio towards objects with
arbitrary positions such as atoms in molecules and materials; and
SchNet as a network designed to respect essential quantum-chemical
constraints, using cfconv layers in R^3 to model interactions of atoms
at arbitrary positions, delivering rotationally INVARIANT energy
predictions and rotationally EQUIVARIANT force predictions.

Gilmer, J., Schoenholz, S. S., Riley, P. F., Vinyals, O. & Dahl, G. E.
(2017) "Neural Message Passing for Quantum Chemistry", *ICML 2017*,
PMLR 70, 1263-1272, arXiv:1704.01212. The framework this instantiates;
implemented in :mod:`mpfn`.
"""

